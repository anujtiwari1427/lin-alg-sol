class ExportService:

    EXPORTERS = {
        'pdf': (PDFExporter, 'application/pdf', '.pdf'),
        'docx': (WordExporter, 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', '.docx'),
        'word': (WordExporter, 'application/vnd.openxmlformats-officedocument.wordprocessingml.document', '.docx'),
        'xlsx': (ExcelExporter, 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', '.xlsx'),
        'excel': (ExcelExporter, 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', '.xlsx'),
        'csv': (CSVExporter, 'text/csv', '.csv'),
        'json': (JSONExporter, 'application/json', '.json'),
        'md': (MarkdownExporter, 'text/markdown', '.md'),
        'markdown': (MarkdownExporter, 'text/markdown', '.md'),
        'tex': (LatexExporter, 'application/x-tex', '.tex'),
        'latex': (LatexExporter, 'application/x-tex', '.tex'),
        'html': (HTMLExporter, 'text/html', '.html'),
        'txt': (TextExporter, 'text/plain', '.txt'),
        'text': (TextExporter, 'text/plain', '.txt')
    }

    @classmethod
    def export(cls, fmt, solution_data, module_name, question_data=None):
        """
        Generate exported content based on format.
        Returns tuple: (file_bytes_or_str, mimetype, filename)
        """
        fmt_key = str(fmt or 'pdf').lower().strip()
        if fmt_key not in cls.EXPORTERS:
            fmt_key = 'pdf'

        exporter_cls, mimetype, ext = cls.EXPORTERS[fmt_key]

        safe_mod = (module_name or 'solution').lower().replace(' ', '_')
        safe_mod = re.sub(r'[^a-z0-9_]', '', safe_mod)
        filename = f"{safe_mod}_report{ext}"

        content = exporter_cls.export(solution_data, module_name, question_data)
        return content, mimetype, filename
