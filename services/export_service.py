        tex.append(r"\item \textbf{Residual:} " + str(v['residual']))
        tex.append(r"\item \textbf{Details:} " + str(v['details']))
        tex.append(r"\end{itemize}")
        tex.append("")

        tex.append(r"\end{document}")
        return "\n".join(tex)


