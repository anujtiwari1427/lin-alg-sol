        r = cls.normalize_report_data(solution_data, module_name, question_data)
        W = 68
        hr = "=" * W
        hr2 = "-" * W

        t = []
        t.append(hr)
        t.append(r['app_name'].center(W))
        t.append(f"Detailed Solution Report — {r['app_version']}".center(W))
        t.append(hr)
        t.append(f"  Operation : {r['operation']}")
        t.append(f"  Date      : {r['date']}  |  Time: {r['time']}")
        t.append(hr)
        t.append("")

        t.append("  [1] INPUT DATA")
        t.append(f"  {hr2}")
        for k, v in r['input'].items():
            t.append(f"  • {k}: {v}")
        t.append("")

        t.append("  [2] MATHEMATICAL THEORY")
        t.append(f"  {hr2}")
        t.append(f"  {r['theory']}")
        t.append("")

        t.append("  [3] FORMULA USED")
        t.append(f"  {hr2}")
        t.append(f"  Formula: {r['formula_plain']}")
        t.append(f"  LaTeX  : {r['formula_latex']}")
        t.append("")

        t.append("  [4] STEP-BY-STEP SOLUTION")
        t.append(f"  {hr2}")
        if r['steps']:
            for st in r['steps']:
                t.append(f"\n  Step {st['step_num']}: {st['title']}")
                if st['text']: t.append(f"    {st['text']}")
                for item in st['list']: t.append(f"    ▸ {item}")
                if st['latex']: t.append(f"    LaTeX: {st['latex']}")
        else:
            t.append("  (No detailed steps recorded)")
        t.append("")

        t.append("  [5] FINAL ANSWER")
        t.append(f"  {hr2}")
        t.append(f"  RESULT: {r['final_answer']['display']}")
        if r['final_answer'].get('latex'):
            t.append(f"  LaTeX : {r['final_answer']['latex']}")
        t.append("")

        t.append("  [6] VERIFICATION")
        t.append(f"  {hr2}")
        v = r['verification']
        t.append(f"  Method  : {v['method']}")
        t.append(f"  Status  : {v['status']}")
        t.append(f"  Residual: {v['residual']}")
        t.append(f"  Details : {v['details']}")
        t.append("")

        t.append(hr)
        t.append(f"  {r['app_name']} {r['app_version']} | {r['date']} {r['time']}")
        t.append(hr)

        return "\n".join(t)


